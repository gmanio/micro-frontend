/** Demo bars for Default story (relative to “today”). */
export function withDemoOccupancy(rooms: InventoryTimelineRoom[]): InventoryTimelineRoom[] {
  const today = new Date();
  const y = today.getFullYear();
  const m = String(today.getMonth() + 1).padStart(2, "0");
  const fmt = (offsetDays: number) => {
    const d = new Date(today);
    d.setDate(d.getDate() + offsetDays);
    const yy = d.getFullYear();
    const mm = String(d.getMonth() + 1).padStart(2, "0");
    const dd = String(d.getDate()).padStart(2, "0");
    return `${yy}-${mm}-${dd}`;
  };

  return rooms.map((room) => {
    if (room.roomNo === "301") {
      return {
        ...room,
        inventoryList: [
          {
            contractId: `C-DEMO-${y}${m}-301`,
            status: "MOVED",
            fromDt: fmt(-45),
            toDt: fmt(60),
            startDt: fmt(-45),
            endDt: fmt(60),
          },
        ],
      };
    }
    if (room.roomNo === "304") {
      return {
        ...room,
        inventoryList: [
          {
            contractId: `C-DEMO-${y}${m}-304`,
            status: "BOOKED",
            fromDt: fmt(10),
            toDt: fmt(100),
            startDt: fmt(10),
            endDt: fmt(100),
          },
        ],
        holdList: [
          {
            contractId: `C-DEMO-${y}${m}-304`,
            status: "MOVED",
            fromDt: fmt(101),
            toDt: fmt(115),
            startDt: fmt(10),
            endDt: fmt(100),
          },
        ],
      };
    }
    if (room.roomNo === "307") {
      return {
        ...room,
        blockList: [
          {
            blockId: 9001,
            blockTyp: "REPAIR",
            status: "ACTIVE",
            fromDt: fmt(-5),
            toDt: fmt(14),
            memo: "수도 점검",
          },
        ],
      };
    }
    if (room.roomNo === "310") {
      return {
        ...room,
        blockList: [
          {
            blockId: 9002,
            blockTyp: "CLEANING",
            status: "ACTIVE",
            fromDt: fmt(2),
            toDt: fmt(5),
          },
        ],
        inventoryList: [
          {
            contractId: `C-DEMO-${y}${m}-310`,
            status: "CONTRACTED",
            fromDt: fmt(20),
            toDt: fmt(80),
            startDt: fmt(20),
            endDt: fmt(80),
          },
        ],
      };
    }
    if (room.roomNo === "314") {
      return {
        ...room,
        inventoryList: [
          {
            contractId: `C-DEMO-${y}${m}-314`,
            status: "MOVED",
            fromDt: fmt(-90),
            toDt: fmt(20),
            startDt: fmt(-90),
            endDt: fmt(20),
            moveOutExpectedDt: fmt(10),
          },
        ],
      };
    }
    return room;
  });
}
